//  ||||||||    ||||||||
//  ||||||||    |||||||└->0 FLOOR  5 INFLUENCED (0 = false / 1 = true)
//  ||||||||    ||||||└-->1 FLOOR  4 INFLUENCED (0 = false / 1 = true)
//  ||||||||    |||||└--->2 FLOOR  3 INFLUENCED (0 = false / 1 = true)
//  ||||||||    ||||└---->3 FLOOR  2 INFLUENCED (0 = false / 1 = true)

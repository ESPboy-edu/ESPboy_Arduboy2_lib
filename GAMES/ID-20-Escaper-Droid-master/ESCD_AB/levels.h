//  ||||||||    ||||||||                                        ||||||||                |||||└--->2  /
//  ||||||||    ||||||||                                        ||||||||                ||||└---->3  \
//  ||||||||    ||||||||                                        ||||||||                |||└----->4   |
//  ||||||||    ||||||||                                        ||||||||                ||└------>5   |  these 5 bits are used to determine on what floor tile the object is
//  ||||||||    ||||||||                                        ||||||||                |└------->6   |
//  ||||||||    ||||||||                                        ||||||||                └-------->7  /   if all 8 bits == 0 => no object
//  ||||||||    ||||||||                                        |||||||| 

//DOOR+STATE  NORTH GOTO  EAST  GOTO  SOUTH GOTO  WEST  GOTO   ENEMY 1      ENEMY 2    OBJECT 3     FLOOR 1     FLOOR 2     FLOOR 3     FLOOR 4     FLOOR 5

//  ||||||||    ||||||||                                        |||└----->4   |
//  ||||||||    ||||||||                                        ||└------>5   |  these 5 bits are used to determine on what floor tile the enemy is
//  ||||||||    ||||||||                                        |└------->6   |
//  ||||||||    ||||||||                                        └-------->7  /   if all 8 bits == 0 => no enemy
//  ||||||||    ||||||||
//  ||||||||    |||||||└->0  \  these 2 bits are used to determine what door you'll go to
//  ||||||||    ||||||└-->1  /
//  ||||||||    |||||└--->2  \

// the logo, written into the display buffer: only the opaque rows of every column are touched
void drawLogo()
{
  uint8_t *buf = arduboy.getBuffer();
  for (byte x = 0; x < LOGO_W; x++)
  {
    byte tb = pgm_read_byte(&logoCol[x]);
    int8_t top = tb >> 3, end = 32 - (tb & 7);             // opaque rows: top .. end-1
    for (byte p = 0; p < 4; p++)
    {
      int8_t lo = top - 8 * p, hi = end - 8 * p;           // the opaque rows inside this page
      if (hi <= 0 || lo >= 8) continue;
      if (lo < 0) lo = 0;
      if (hi > 8) hi = 8;
      byte m = (byte)(0xFF << lo) & (byte)(0xFF >> (8 - hi));
      byte *d = &buf[(LOGO_PAGE + p) * 128 + LOGO_X + x];
      *d = (*d & ~m) | (pgm_read_byte(&logoImg[p * LOGO_W + x]) & m);
    }
  }
}


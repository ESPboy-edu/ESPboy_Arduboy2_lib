#!/usr/bin/env python3
"""
Pocket Stage - the menu font, and the small pictures of the menus.

  python3 tools/font.py     writes PocketStage/font.h: capitals, digits and a few
                            marks from Impact, eleven pixels tall, each a sprite
                            the Arduboy2 library draws; and the pick that is the
                            cursor and the stars, drawn here

ui.h writes with them; the small print stays the library's font.
"""
import os

from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
FONT = "/System/Library/Fonts/Supplemental/Impact.ttf"
HEADER = os.path.join(ROOT, "PocketStage", "font.h")
SIZE = 14
CHARS = " !%&'+,-./0123456789:<>?ABCDEFGHIJKLMNOPQRSTUVWXYZ"
SPACE_W = 3

PICTURES = {
    "PICK": [".##...",
             ".####.",
             ".#####",
             ".#####",
             ".#####",
             ".#####",
             ".####.",
             ".##..."],
    "STAR": ["...#...",
             "...#...",
             "#######",
             ".#####.",
             "..###..",
             ".##.##.",
             "#.....#"],
    "STAR_HOLLOW": ["...#...",
                    "..#.#..",
                    "##...##",
                    "#.....#",
                    ".#...#.",
                    ".#.#.#.",
                    "#.....#"],
}


def glyphs():
    """-> {char: bitmap}, all the same height, the capitals' height"""
    font = ImageFont.truetype(FONT, SIZE)
    _, top, _, base = font.getbbox("H")
    h = base - top
    out = {}
    for ch in CHARS:
        if ch == " ":
            out[ch] = Image.new("1", (SPACE_W, h), 0)
            continue
        l, _, r, _ = font.getbbox(ch)
        im = Image.new("L", (r - l + 2, h), 0)
        ImageDraw.Draw(im).text((-l + 1, -top), ch, font=font, fill=255)
        im = im.point(lambda v: 255 if v >= 128 else 0).convert("1")
        box = im.getbbox()
        out[ch] = im.crop((box[0], 0, box[2], h)) if box else im.crop((0, 0, 1, h))
    return out, h


def sprite(im):
    """a bitmap -> the Arduboy sprite: width, height, then the pixels a
    column at a time, eight rows to a byte, top row in bit 0"""
    w, h = im.size
    px = im.load()
    out = [w, h]
    for page in range((h + 7) // 8):
        for x in range(w):
            b = 0
            for i in range(8):
                y = page * 8 + i
                if y < h and px[x, y]:
                    b |= 1 << i
            out.append(b)
    return out


def picture(rows):
    im = Image.new("1", (len(rows[0]), len(rows)), 0)
    px = im.load()
    for y, row in enumerate(rows):
        for x, c in enumerate(row):
            if c == "#":
                px[x, y] = 1
    return im


def c_bytes(name, values, note):
    lines = []
    for i in range(0, len(values), 16):
        lines.append("  " + ", ".join("0x%02x" % v for v in values[i:i + 16]) + ",")
    return "// %s\nstatic const uint8_t %s[] PROGMEM = {\n%s\n};\n\n" % (note, name, "\n".join(lines))


def main():
    gl, h = glyphs()
    data = []
    offsets = {}
    for ch in CHARS:
        offsets[ch] = len(data)
        data += sprite(gl[ch])
    first, last = 32, ord("Z")
    table = [offsets.get(chr(c), 0xFFFF) for c in range(first, last + 1)]
    with open(HEADER, "w") as f:
        f.write("// Generated by tools/font.py - do not edit by hand.\n#pragma once\n#include <avr/pgmspace.h>\n\n")
        f.write("#define FONT_H %d\n#define FONT_FIRST %d\n#define FONT_LAST %d\n\n" % (h, first, last))
        f.write(c_bytes("FONT_DATA", data, "the glyphs, one sprite after another"))
        lines = ["  " + ", ".join("0x%04x" % v for v in table[i:i + 12]) + "," for i in range(0, len(table), 12)]
        f.write("// where each character from FONT_FIRST on starts in FONT_DATA; 0xFFFF = not in the font\n"
                "static const uint16_t FONT_OFFSET[%d] PROGMEM = {\n%s\n};\n\n" % (len(table), "\n".join(lines)))
        for name, rows in PICTURES.items():
            f.write(c_bytes(name, sprite(picture(rows)), name.lower().replace("_", " ")))
    print("font: %d glyphs, %d px tall, %d bytes; %s" % (len(CHARS), h, len(data), os.path.relpath(HEADER, ROOT)))


if __name__ == "__main__":
    main()
